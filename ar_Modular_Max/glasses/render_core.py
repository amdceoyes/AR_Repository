    def _project_to_screen(self, pose):
        """
        将空间3D坐标投影到2D眼镜屏幕上
        
        参数:
        pose: 4x4位姿矩阵，表示3D空间中的位置和朝向
        
        返回:
        投影后的2D屏幕坐标(x, y)
        
        这是计算机图形学和计算机视觉中的核心问题
        真实投影过程包括：
        1. 模型变换：从模型坐标到世界坐标
        2. 视图变换：从世界坐标到相机坐标
        3. 投影变换：从3D相机坐标到2D标准化设备坐标
        4. 视口变换：到屏幕像素坐标
        
        简化实现：这里只是从位姿矩阵中提取平移分量并缩放
        """
        # 使用相机内参进行投影变换
        # 简化实现：从位姿矩阵提取平移分量并缩放
        
        # 位姿矩阵格式：
        # [[R00, R01, R02, tx],
        #  [R10, R11, R12, ty],
        #  [R20, R21, R22, tz],
        #  [ 0,   0,   0,  1]]
        
        # 提取x和y方向的平移量（第4列的前3个元素）
        tx = pose[0][3]  # x方向平移
        ty = pose[1][3]  # y方向平移
        tz = pose[2][3]  # z方向平移（深度）
        
        # 这里只是简化模拟：将3D坐标乘以100得到屏幕坐标
        # 真实投影需要：
        # 1. 相机内参矩阵（焦距、主点）
        # 2. 考虑镜头畸变
        # 3. 深度测试
        # 4. 裁剪空间转换
        
        # 简单缩放得到屏幕坐标
        screen_x = tx * 100
        screen_y = ty * 100
        
        return (screen_x, screen_y)  # 模拟坐标计算